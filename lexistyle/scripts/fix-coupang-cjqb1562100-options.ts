import "dotenv/config";
import { mkdir, writeFile } from "node:fs/promises";
import { coupangRequest } from "../src/lib/channels/coupang/client";

const SELLER_PRODUCT_ID = "16405131320";
const pairs = [
  ["그레이", "S"], ["그레이", "M"], ["그레이", "L"],
  ["블랙", "S"], ["블랙", "M"], ["블랙", "L"],
  ["카키", "S"], ["카키", "M"], ["카키", "L"],
] as const;

async function main() {
  const path = `/v2/providers/seller_api/apis/api/v1/marketplace/seller-products/${SELLER_PRODUCT_ID}`;
  const current = await coupangRequest("GET", path) as Record<string, any>;
  const omitTop = new Set([
    "trackingId", "categoryId", "productId", "mdId", "mdName", "statusName", "codBaseDeliveryCharge",
    "installationCharge", "additionalDeliveryChargeEnabled", "additionalInstallationChargeEnabled", "bundlePackingDelivery",
    "exchangeType", "contributorType", "sellerUId", "extraInfoMessage", "manufacture", "productOrigin", "roleCode",
    "status", "bundleInfo", "multiShippingInfos", "multiReturnInfos", "confirmationToken",
  ]);
  const omitItem = new Set([
    "itemId", "supplyPrice", "freePriceType", "bestPriceGuaranteed3P", "saleAgentCommission", "autoPricingInfoView",
    "sameDayShipping", "isAutoGenerated", "subRegistrationType",
  ]);
  const body = Object.fromEntries(Object.entries(current).filter(([key]) => !omitTop.has(key)));
  body.requested = true;
  body.items = (current.items ?? []).map((item: Record<string, any>, index: number) => {
    const [color, size] = pairs[index]!;
    const cleaned = Object.fromEntries(Object.entries(item).filter(([key]) => !omitItem.has(key)));
    cleaned.itemName = `${color} / ${size}`;
    cleaned.attributes = [
      { attributeTypeName: "색상", attributeValueName: color },
      { attributeTypeName: "패션의류/잡화 사이즈", attributeValueName: size },
    ];
    cleaned.images = (item.images ?? []).map((image: Record<string, any>) => ({
      imageOrder: image.imageOrder,
      imageType: image.imageType,
      vendorPath: image.cdnPath ? `http://image1.coupangcdn.com/image/${image.cdnPath}` : image.vendorPath,
    }));
    return cleaned;
  });
  await mkdir("tmp/coupang", { recursive: true });
  await writeFile("tmp/coupang/CJQB1562100-option-fix-request.json", JSON.stringify(body, null, 2));
  const response = await coupangRequest("PUT", "/v2/providers/seller_api/apis/api/v1/marketplace/seller-products", "", body);
  console.log(JSON.stringify({ sellerProductId: SELLER_PRODUCT_ID, response }, null, 2));
  process.exit(0);
}

main().catch((error) => { console.error(error instanceof Error ? error.message : error); process.exit(1); });
