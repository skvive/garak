/**
 * 쿠팡 16406104949 상세 HTML 갱신 — 잘못된 detail-collar/button/cuff 크롭 제거본 반영
 * Usage: npx tsx scripts/update-cjyd2717187-coupang-detail.ts [--apply]
 */
import { config } from "dotenv";
config({ path: ".env.local", quiet: true });
config({ path: ".env", quiet: true });
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { coupangRequest } from "../src/lib/channels/coupang/client";

const LISTING_ID = "16406104949";
const ROOT = path.resolve("public/pdp/cjyd2717187-trench-long");
const FRAGMENT = "pdp-site/womens-long-suede-trench-coat/coupang/v1/detail-fragment.html";
const PRODUCT_PATH = "/v2/providers/seller_api/apis/api/v1/marketplace/seller-products";

const READ_ONLY_TOP_KEYS = new Set([
  "trackingId", "categoryId", "productId", "mdId", "mdName", "statusName", "codBaseDeliveryCharge",
  "installationCharge", "additionalDeliveryChargeEnabled", "additionalInstallationChargeEnabled",
  "bundlePackingDelivery", "exchangeType", "contributorType", "sellerUId", "extraInfoMessage", "manufacture",
  "productOrigin", "roleCode", "status", "bundleInfo", "multiShippingInfos", "multiReturnInfos", "confirmationToken",
]);
const READ_ONLY_ITEM_KEYS = new Set([
  "itemId", "supplyPrice", "freePriceType", "bestPriceGuaranteed3P", "saleAgentCommission",
  "autoPricingInfoView", "sameDayShipping", "isAutoGenerated", "subRegistrationType", "vendorItemId",
]);

type Row = Record<string, unknown>;

async function main() {
  const apply = process.argv.includes("--apply");
  const contents = readFileSync(FRAGMENT, "utf8");
  if (/detail-collar|detail-cuff|detail-button|NOTCHED LAPEL|CUFF STRAP/.test(contents)) {
    throw new Error("fragment still contains removed detail blocks");
  }

  const live = (await coupangRequest("GET", `${PRODUCT_PATH}/${LISTING_ID}`, "")) as Row & { items: Row[] };
  if (!live.items?.length) throw new Error("items empty");

  const body = Object.fromEntries(Object.entries(live).filter(([key]) => !READ_ONLY_TOP_KEYS.has(key))) as Row & { items: Row[] };
  body.requested = true;
  body.items = live.items.map((item) => {
    const cleaned = Object.fromEntries(Object.entries(item).filter(([key]) => !READ_ONLY_ITEM_KEYS.has(key))) as Row;
    cleaned.images = ((item.images as Row[] | undefined) ?? []).map((image) => ({
      imageOrder: image.imageOrder,
      imageType: image.imageType,
      vendorPath: image.cdnPath ? `http://image1.coupangcdn.com/image/${image.cdnPath}` : image.vendorPath,
    }));
    cleaned.attributes = ((item.attributes as Row[] | undefined) ?? [])
      .filter((attribute) => attribute.attributeValueName)
      .map((attribute) => ({
        attributeTypeName: attribute.attributeTypeName,
        attributeValueName: attribute.attributeValueName,
      }));
    cleaned.contents = [{ contentsType: "HTML", contentDetails: [{ content: contents, detailType: "TEXT" }] }];
    return cleaned;
  });

  writeFileSync("tmp/cp-trench-long-put-body.json", JSON.stringify(body, null, 1), "utf8");
  console.log(JSON.stringify({
    id: LISTING_ID,
    status: live.statusName,
    contentsChars: contents.length,
    hasBadDetail: /detail-collar|detail-cuff/.test(contents),
    apply,
  }, null, 2));

  if (!apply) {
    console.log("dry-run — re-run with --apply");
    return;
  }

  const result = await coupangRequest("PUT", PRODUCT_PATH, "", body);
  const after = (await coupangRequest("GET", `${PRODUCT_PATH}/${LISTING_ID}`, "")) as Row & { items: Row[] };
  const receipt = {
    sellerProductId: LISTING_ID,
    putResult: result,
    statusAfter: after.statusName ?? after.status,
    contentsChars: contents.length,
    updatedAt: new Date().toISOString(),
  };
  writeFileSync(path.join(ROOT, "coupang-detail-update-receipt.json"), JSON.stringify(receipt, null, 2));
  console.log(JSON.stringify(receipt, null, 2));
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
