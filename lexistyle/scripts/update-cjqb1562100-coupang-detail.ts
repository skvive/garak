/**
 * 쿠팡 상품 16405228414 (LEXI 여성 루즈핏 미디 트렌치 코트 벨트세트)의 상세페이지(contents HTML)를
 * 추천 포맷 v1(pdp-site/womens-belted-cuff-trench-coat/coupang/v1/detail-fragment.html)로 교체한다.
 *
 * - 상품명·옵션·가격·재고·고시정보·검색태그는 라이브 값을 그대로 되돌려 보내고 contents만 바꾼다.
 * - 기본은 드라이런(tmp/cp-put-body.json 기록 + 요약 출력). 실제 전송은 --apply 를 붙인다.
 * - PUT 은 쿠팡 "상품 수정 요청"이라 심의가 다시 돌 수 있다(승인완료 → 심의중).
 *
 * Usage: npx tsx scripts/update-cjqb1562100-coupang-detail.ts [--apply]
 */
import { config } from "dotenv";
config({ path: ".env.local", quiet: true });
config({ path: ".env", quiet: true });
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const LISTING_ID = "16405228414";
const ROOT = path.resolve("public/pdp/cjqb1562100-trench");
const FRAGMENT = "pdp-site/womens-belted-cuff-trench-coat/coupang/v1/detail-fragment.html";
const PRODUCT_PATH = "/v2/providers/seller_api/apis/api/v1/marketplace/seller-products";

/** 등록(POST) 스키마와 동일한 키만 골라 되돌려 보낸다. 조회 전용(statusName·productId·categoryId…)은 제외. */
const READ_ONLY_TOP_KEYS = new Set([
  "trackingId", "categoryId", "productId", "mdId", "mdName", "statusName", "codBaseDeliveryCharge",
  "installationCharge", "additionalDeliveryChargeEnabled", "additionalInstallationChargeEnabled",
  "bundlePackingDelivery", "exchangeType", "contributorType", "sellerUId", "extraInfoMessage", "manufacture",
  "productOrigin", "roleCode", "status", "bundleInfo", "multiShippingInfos", "multiReturnInfos", "confirmationToken",
]);

const READ_ONLY_ITEM_KEYS = new Set([
  "itemId", "supplyPrice", "freePriceType", "bestPriceGuaranteed3P", "saleAgentCommission",
  "autoPricingInfoView", "sameDayShipping", "isAutoGenerated", "subRegistrationType",
]);

type Row = Record<string, unknown>;

async function main() {
  const apply = process.argv.includes("--apply");
  const { coupangRequest } = await import("../src/lib/channels/coupang/client");

  const live = (await coupangRequest("GET", `${PRODUCT_PATH}/${LISTING_ID}`, "")) as Row & { items: Row[] };
  const contents = readFileSync(FRAGMENT, "utf8");
  if (!live.items?.length) throw new Error("라이브 상품 아이템을 확인할 수 없습니다.");

  const liveContents = String(
    (live.items[0].contents as { contentDetails?: { content?: string }[] }[] | undefined)?.[0]?.contentDetails?.[0]?.content ?? ""
  );

  const body = Object.fromEntries(Object.entries(live).filter(([key]) => !READ_ONLY_TOP_KEYS.has(key))) as Row & { items: Row[] };
  body.requested = true;
  body.items = live.items.map((item) => {
    const cleaned = Object.fromEntries(Object.entries(item).filter(([key]) => !READ_ONLY_ITEM_KEYS.has(key))) as Row;
    cleaned.images = (item.images as Row[] | undefined ?? []).map((image) => ({
      imageOrder: image.imageOrder,
      imageType: image.imageType,
      vendorPath: image.cdnPath ? `http://image1.coupangcdn.com/image/${image.cdnPath}` : image.vendorPath,
    }));
    cleaned.attributes = (item.attributes as Row[] | undefined ?? [])
      .filter((attribute) => attribute.attributeValueName)
      .map((attribute) => ({
        attributeTypeName: attribute.attributeTypeName,
        attributeValueName: attribute.attributeValueName,
      }));
    cleaned.contents = [{ contentsType: "HTML", contentDetails: [{ content: contents, detailType: "TEXT" }] }];
    return cleaned;
  });

  const bodyPath = path.join("tmp", "cp-put-body.json");
  writeFileSync(bodyPath, JSON.stringify(body, null, 1), "utf8");
  console.log("상품:", String(live.sellerProductName), "| 현재 상태:", String(live.statusName), "| 아이템:", live.items.length);
  console.log("contents:", liveContents.length, "→", contents.length, "chars");
  console.log("보낼 키:", Object.keys(body).join(", "));
  console.log("아이템 키:", Object.keys((body.items[0] ?? {}) as Row).join(", "));
  console.log("가격 유지:", live.items.map((i) => `${i.salePrice}/${i.originalPrice}`).join(" "));
  console.log("드라이런 본문:", bodyPath, "| 실행하려면 --apply");

  if (!apply) return;
  const result = await coupangRequest("PUT", PRODUCT_PATH, "", body);
  const receiptPath = path.join(ROOT, "coupang-replacement-receipt.json");
  const receipt = JSON.parse(readFileSync(receiptPath, "utf8")) as Row;
  writeFileSync(
    receiptPath,
    JSON.stringify({ ...receipt, detail: { version: "v1-recommended", contentsChars: contents.length, fragment: FRAGMENT, appliedAt: new Date().toISOString() }, updateResult: result }, null, 2),
    "utf8"
  );
  console.log("PUT 결과:", JSON.stringify(result));
}

if (process.argv[1]?.includes("update-cjqb1562100-coupang-detail")) {
  main().catch((error) => {
    console.error("FAIL", error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
