import { config } from "dotenv";
config({ path: ".env.local", quiet: true });
config({ path: ".env", quiet: true });
import { writeFileSync } from "node:fs";
import path from "node:path";
import { coupangRequest } from "../src/lib/channels/coupang/client";

const LISTING_ID = "16406053508";
const PRODUCT_PATH = "/v2/providers/seller_api/apis/api/v1/marketplace/seller-products";
const ROOT = path.resolve("public/pdp/cjtw3189049-sport-set");

const READ_ONLY_TOP_KEYS = new Set([
  "trackingId", "categoryId", "productId", "mdId", "mdName", "statusName", "codBaseDeliveryCharge",
  "installationCharge", "additionalDeliveryChargeEnabled", "additionalInstallationChargeEnabled",
  "bundlePackingDelivery", "exchangeType", "contributorType", "sellerUId", "extraInfoMessage", "manufacture",
  "productOrigin", "roleCode", "status", "bundleInfo", "multiShippingInfos", "multiReturnInfos", "confirmationToken",
]);
const READ_ONLY_ITEM_KEYS = new Set([
  "itemId", "supplyPrice", "freePriceType", "bestPriceGuaranteed3P", "saleAgentCommission",
  "autoPricingInfoView", "sameDayShipping", "isAutoGenerated", "subRegistrationType", "vendorItemId",
]);

type Row = Record<string, unknown>;

function clothingNotices(phone: string) {
  return [
    { noticeCategoryName: "의류", noticeCategoryDetailName: "제품 소재", content: "폴리에스터 · 플리스 안감" },
    { noticeCategoryName: "의류", noticeCategoryDetailName: "색상", content: "브라운 / 스카이블루 / 라이트퍼플" },
    { noticeCategoryName: "의류", noticeCategoryDetailName: "치수", content: "S · M · L · XL · 2XL · 3XL (상세페이지 사이즈표 참조)" },
    { noticeCategoryName: "의류", noticeCategoryDetailName: "제조자(수입자)", content: "상세페이지 참조" },
    { noticeCategoryName: "의류", noticeCategoryDetailName: "제조국", content: "중국" },
    { noticeCategoryName: "의류", noticeCategoryDetailName: "세탁방법 및 취급시 주의사항", content: "세탁 전 제품 라벨의 관리 방법을 확인해 주세요" },
    { noticeCategoryName: "의류", noticeCategoryDetailName: "제조연월", content: "상세페이지 참조" },
    { noticeCategoryName: "의류", noticeCategoryDetailName: "품질보증기준", content: "관련 법 및 소비자분쟁해결 기준에 따름" },
    { noticeCategoryName: "의류", noticeCategoryDetailName: "A/S 책임자와 전화번호", content: phone },
  ];
}

async function main() {
  const apply = process.argv.includes("--apply");
  const phone = process.env.COUPANG_COMPANY_CONTACT_NUMBER || "상세페이지 참조";
  const live = (await coupangRequest("GET", `${PRODUCT_PATH}/${LISTING_ID}`, "")) as Row & { items: Row[] };
  if (!live.items?.length) throw new Error("items empty");

  const notices = clothingNotices(phone);
  const body = Object.fromEntries(Object.entries(live).filter(([key]) => !READ_ONLY_TOP_KEYS.has(key))) as Row & { items: Row[] };
  body.requested = true;
  body.items = live.items.map((item) => {
    const cleaned = Object.fromEntries(Object.entries(item).filter(([key]) => !READ_ONLY_ITEM_KEYS.has(key))) as Row;
    cleaned.images = ((item.images as Row[] | undefined) ?? []).map((image) => ({
      imageOrder: image.imageOrder,
      imageType: image.imageType,
      vendorPath: image.cdnPath ? `http://image1.coupangcdn.com/image/${image.cdnPath}` : image.vendorPath,
    }));
    cleaned.attributes = ((item.attributes as Row[] | undefined) ?? [])
      .filter((attribute) => attribute.attributeValueName)
      .map((attribute) => ({
        attributeTypeName: attribute.attributeTypeName,
        attributeValueName: attribute.attributeValueName,
      }));
    cleaned.notices = notices;
    cleaned.overseasPurchased = "OVERSEAS_PURCHASED";
    cleaned.pccNeeded = true;
    return cleaned;
  });

  writeFileSync("tmp/cp-sport-repair-body.json", JSON.stringify(body, null, 1), "utf8");
  console.log(JSON.stringify({
    id: LISTING_ID,
    status: live.statusName,
    noticeBefore: (live.items[0].notices as Row[] | undefined)?.[0]?.noticeCategoryName,
    noticeAfter: notices[0]?.noticeCategoryName,
    noticeCount: notices.length,
    optionCount: body.items.length,
    apply,
  }, null, 2));

  if (!apply) {
    console.log("dry-run only — re-run with --apply");
    return;
  }

  const result = await coupangRequest("PUT", PRODUCT_PATH, "", body);
  const after = (await coupangRequest("GET", `${PRODUCT_PATH}/${LISTING_ID}`, "")) as Row & { items: Row[] };
  const receipt = {
    sellerProductId: LISTING_ID,
    putResult: result,
    statusAfter: after.statusName ?? after.status,
    noticeCategory: (after.items?.[0]?.notices as Row[] | undefined)?.[0]?.noticeCategoryName,
    optionSample: (after.items ?? []).slice(0, 2).map((it) => ({
      itemName: it.itemName,
      externalVendorSku: it.externalVendorSku,
      salePrice: it.salePrice,
      attributes: it.attributes,
    })),
    repairedAt: new Date().toISOString(),
  };
  writeFileSync(path.join(ROOT, "coupang-repair-receipt.json"), JSON.stringify(receipt, null, 2));
  console.log(JSON.stringify(receipt, null, 2));
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
