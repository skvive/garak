import { config } from "dotenv";
config({ path: ".env.local", quiet: true });
config({ path: ".env", quiet: true });
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { coupangRequest } from "../src/lib/channels/coupang/client";

const LISTING_ID = "16405322832";
const PRODUCT_PATH = "/v2/providers/seller_api/apis/api/v1/marketplace/seller-products";
const ROOT = path.resolve("public/pdp/cjls3061165-pink-tweed");

/** 갤러리에서 제거할 CDN path 조각 (짧은 머리 스튜디오 착용컷) */
const REMOVE_GALLERY_FRAGMENTS = [
  "be0c/af1ac72134c7b73b9ac39e6d786224f3ce6de73116fec467e14c4a13d11e",
];
/** 상세 HTML에서 제거할 이미지 URL 조각 */
const REMOVE_CONTENT_FRAGMENTS = [
  "01a2/6cd8212c6679b9f40e5f43e144a9847d2033c5567d4885bbb3abcb1437e6",
  "original-look.jpg",
];

const READ_ONLY_TOP_KEYS = new Set([
  "trackingId", "categoryId", "productId", "mdId", "mdName", "statusName", "codBaseDeliveryCharge",
  "installationCharge", "additionalDeliveryChargeEnabled", "additionalInstallationChargeEnabled",
  "bundlePackingDelivery", "exchangeType", "contributorType", "sellerUId", "extraInfoMessage", "manufacture",
  "productOrigin", "roleCode", "status", "bundleInfo", "multiShippingInfos", "multiReturnInfos", "confirmationToken",
]);
const READ_ONLY_ITEM_KEYS = new Set([
  "itemId", "supplyPrice", "freePriceType", "bestPriceGuaranteed3P", "saleAgentCommission",
  "autoPricingInfoView", "sameDayShipping", "isAutoGenerated", "subRegistrationType", "vendorItemId",
]);

type Row = Record<string, unknown>;

function stripModelImg(html: string): string {
  let out = html;
  // <img ... src="...fragment..." ...> 전체 태그 제거
  out = out.replace(/<img\b[^>]*>/gi, (tag) => {
    if (REMOVE_CONTENT_FRAGMENTS.some((f) => tag.includes(f))) return "";
    return tag;
  });
  return out;
}

function cleanImages(images: Row[]): Row[] {
  const kept = images.filter((image) => {
    const pathStr = String(image.cdnPath || image.vendorPath || image.imagePath || "");
    return !REMOVE_GALLERY_FRAGMENTS.some((f) => pathStr.includes(f));
  });
  return kept.map((image, i) => ({
    imageOrder: i,
    imageType: i === 0 ? "REPRESENTATION" : "DETAIL",
    vendorPath: image.cdnPath
      ? `http://image1.coupangcdn.com/image/${image.cdnPath}`
      : image.vendorPath,
  }));
}

async function main() {
  const apply = process.argv.includes("--apply");
  mkdirSync("tmp", { recursive: true });

  const live = (await coupangRequest("GET", `${PRODUCT_PATH}/${LISTING_ID}`, "")) as Row & { items: Row[] };
  if (!live.items?.length) throw new Error("items empty");

  const beforeImages = ((live.items[0]?.images as Row[]) ?? []).map((i) => i.cdnPath || i.vendorPath);
  const beforeContent = String(
    ((live.items[0]?.contents as any[])?.[0]?.contentDetails?.[0]?.content) ?? "",
  );
  const afterContent = stripModelImg(beforeContent);

  const body = Object.fromEntries(Object.entries(live).filter(([key]) => !READ_ONLY_TOP_KEYS.has(key))) as Row & {
    items: Row[];
  };
  body.requested = true;
  body.items = live.items.map((item) => {
    const cleaned = Object.fromEntries(Object.entries(item).filter(([key]) => !READ_ONLY_ITEM_KEYS.has(key))) as Row;
    cleaned.images = cleanImages((item.images as Row[] | undefined) ?? []);
    cleaned.attributes = ((item.attributes as Row[] | undefined) ?? [])
      .filter((attribute) => attribute.attributeValueName)
      .map((attribute) => ({
        attributeTypeName: attribute.attributeTypeName,
        attributeValueName: attribute.attributeValueName,
      }));
    const content = stripModelImg(
      String(((item.contents as any[])?.[0]?.contentDetails?.[0]?.content) ?? afterContent),
    );
    cleaned.contents = [{ contentsType: "HTML", contentDetails: [{ content, detailType: "TEXT" }] }];
    return cleaned;
  });

  writeFileSync("tmp/cp-pink-tweed-remove-look-body.json", JSON.stringify(body, null, 1), "utf8");
  const summary = {
    id: LISTING_ID,
    apply,
    status: live.statusName,
    imagesBefore: beforeImages.length,
    imagesAfter: (body.items[0]?.images as Row[])?.length,
    removedGallery: beforeImages.filter((p) =>
      REMOVE_GALLERY_FRAGMENTS.some((f) => String(p).includes(f)),
    ),
    contentCharsBefore: beforeContent.length,
    contentCharsAfter: afterContent.length,
    contentStillHasLook: REMOVE_CONTENT_FRAGMENTS.some((f) => afterContent.includes(f)),
  };
  console.log(JSON.stringify(summary, null, 2));

  if (!apply) {
    console.log("dry-run — re-run with --apply");
    return;
  }

  const result = await coupangRequest("PUT", PRODUCT_PATH, "", body);
  // 반영 대기 후 재조회
  for (let i = 0; i < 12; i++) {
    await new Promise((r) => setTimeout(r, 10000));
    try {
      const after = (await coupangRequest("GET", `${PRODUCT_PATH}/${LISTING_ID}`, "")) as Row & { items: Row[] };
      const imgs = ((after.items?.[0]?.images as Row[]) ?? []).map((i) => i.cdnPath || i.vendorPath);
      const content = String(((after.items?.[0]?.contents as any[])?.[0]?.contentDetails?.[0]?.content) ?? "");
      const receipt = {
        sellerProductId: LISTING_ID,
        productId: after.productId,
        putResult: result,
        statusAfter: after.statusName ?? after.status,
        imagesAfter: imgs,
        galleryStillHasLook: imgs.some((p) => REMOVE_GALLERY_FRAGMENTS.some((f) => String(p).includes(f))),
        contentStillHasLook: REMOVE_CONTENT_FRAGMENTS.some((f) => content.includes(f)),
        updatedAt: new Date().toISOString(),
      };
      writeFileSync(path.join(ROOT, "coupang-remove-original-look-receipt.json"), JSON.stringify(receipt, null, 2));
      console.log(JSON.stringify(receipt, null, 2));
      if (!receipt.galleryStillHasLook && !receipt.contentStillHasLook) return;
      if (String(after.statusName).includes("승인") || after.status === "APPROVED") {
        // 아직 이전 콘텐츠일 수 있음 — 계속 폴링
      }
    } catch (e) {
      console.log(JSON.stringify({ poll: i + 1, error: e instanceof Error ? e.message : String(e) }));
    }
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
