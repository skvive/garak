import { config } from "dotenv";
config({ path: ".env.local", quiet: true });
config({ path: ".env", quiet: true });
import { readFileSync, writeFileSync } from "node:fs";
import { coupangRequest } from "../src/lib/channels/coupang/client";

const LISTING_ID = "16406104949";
const TITLE = "LEXI 가을맞이 트렌치코트 해외직구 선착순";
const DRAFT = "tmp/pdp-fix-trench/draft";
const PRODUCT_PATH = "/v2/providers/seller_api/apis/api/v1/marketplace/seller-products";
const READ_ONLY_TOP_KEYS = new Set([
  "trackingId", "categoryId", "productId", "mdId", "mdName", "statusName", "codBaseDeliveryCharge",
  "installationCharge", "additionalDeliveryChargeEnabled", "additionalInstallationChargeEnabled",
  "bundlePackingDelivery", "exchangeType", "contributorType", "sellerUId", "extraInfoMessage", "manufacture",
  "productOrigin", "roleCode", "status", "bundleInfo", "multiShippingInfos", "multiReturnInfos", "confirmationToken",
]);
const READ_ONLY_ITEM_KEYS = new Set([
  "itemId", "supplyPrice", "freePriceType", "bestPriceGuaranteed3P", "saleAgentCommission",
  "autoPricingInfoView", "sameDayShipping", "isAutoGenerated", "subRegistrationType", "vendorItemId",
]);
type Row = Record<string, unknown>;

async function main() {
  const apply = process.argv.includes("--apply");
  let html = readFileSync(`${DRAFT}/draft.html`, "utf8");
  html = html.slice(html.indexOf('<div class="lexi-pdp"'), html.lastIndexOf("</body>")).trim();
  const names = [...new Set([...html.matchAll(/src="\.\/([^"]+\.jpg)"/g)].map((m) => m[1]))];
  const urls: Record<string, string> = {};
  if (apply) {
    const { put } = await import("@vercel/blob");
    for (const n of names) {
      const r = await put(`coupang/CJYD2717187/v2/${n}`, readFileSync(`${DRAFT}/${n}`), { access: "public", contentType: "image/jpeg", addRandomSuffix: false, allowOverwrite: true });
      urls[n] = r.url;
    }
    for (const n of names) html = html.split(`./${n}`).join(urls[n]);
  }
  const live = (await coupangRequest("GET", `${PRODUCT_PATH}/${LISTING_ID}`, "")) as Row & { items: Row[] };
  const body = Object.fromEntries(Object.entries(live).filter(([k]) => !READ_ONLY_TOP_KEYS.has(k))) as Row & { items: Row[] };
  const before = { sellerProductName: live.sellerProductName, displayProductName: live.displayProductName, generalProductName: live.generalProductName };
  body.requested = true;
  body.sellerProductName = TITLE;
  if ("displayProductName" in body) body.displayProductName = TITLE;
  if ("generalProductName" in body) body.generalProductName = TITLE;
  body.items = live.items.map((item) => {
    const c = Object.fromEntries(Object.entries(item).filter(([k]) => !READ_ONLY_ITEM_KEYS.has(k))) as Row;
    c.images = ((item.images as Row[] | undefined) ?? []).map((im) => ({ imageOrder: im.imageOrder, imageType: im.imageType, vendorPath: im.cdnPath ? `http://image1.coupangcdn.com/image/${im.cdnPath}` : im.vendorPath }));
    c.attributes = ((item.attributes as Row[] | undefined) ?? []).filter((a) => a.attributeValueName).map((a) => ({ attributeTypeName: a.attributeTypeName, attributeValueName: a.attributeValueName }));
    c.contents = [{ contentsType: "HTML", contentDetails: [{ content: html, detailType: "TEXT" }] }];
    return c;
  });
  writeFileSync("tmp/cp-trench-v2-put-body.json", JSON.stringify(body, null, 1), "utf8");
  console.log(JSON.stringify({ id: LISTING_ID, status: live.statusName, before, after: TITLE, items: live.items.map((i) => i.itemName), images: names.length, htmlChars: html.length, apply }, null, 1));
  if (!apply) return console.log("dry-run — re-run with --apply");
  const result = await coupangRequest("PUT", PRODUCT_PATH, "", body);
  const after = (await coupangRequest("GET", `${PRODUCT_PATH}/${LISTING_ID}`, "")) as Row;
  console.log(JSON.stringify({ putResult: result, statusAfter: after.statusName, nameAfter: after.sellerProductName }, null, 1));
}
main().catch((e) => { console.error(e instanceof Error ? e.message : e); process.exit(1); });
