/** slug → 배치 오버라이드 (없으면 null) */
export function getSample3BatchOverride(slug: string): { html: string; structured: PdpStructured; assetUrls: string[] } | null {
  for (const d of batchDefs) {
    if (slug.startsWith(d.prefix)) {
      return { html: renderBatchHtml(d), structured: buildStructured(d), assetUrls: d.assets };
    }
  }
  return null;
}

export function countBatchOverrides(): number {
  return batchDefs.length;
}
